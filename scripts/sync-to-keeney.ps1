<#
.SYNOPSIS
    Mirrors the portal application from this repository into the KEENEY clone.

.DESCRIPTION
    Copies the application paths (app, bootstrap, config, database, lang, resources,
    routes, tests, public without public/vendor/nova, the storage skeleton, docs/PORTAL.md
    and the root project files) into the KEENEY repository, deletes files there that no
    longer exist here, then checks the clone and prints its git status with a suggested
    commit message. It never commits or pushes, and it never touches the platform files
    (README.md, Dockerfile, pipelines, site.json, ignore files, ...).

    The file list comes from git (tracked files plus untracked files that are not
    ignored), so local artefacts such as vendor/, public/build or storage/azurite are
    never copied. Windows PowerShell 5.1 compatible.

.PARAMETER Target
    The KEENEY clone. Default: D:\WORK\Avedsoft\Kevin\Portal\keeneycs-shn-portal

.PARAMETER Git
    Path to git.exe. Default: git on PATH, else the newest GitHub Desktop copy.

.PARAMETER DryRun
    Show what would be copied and deleted without changing the clone.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File scripts\sync-to-keeney.ps1 -DryRun
#>
[CmdletBinding()]
param(
    [string] $Source = '',
    [string] $Target = 'D:\WORK\Avedsoft\Kevin\Portal\keeneycs-shn-portal',
    [string] $Git = '',
    [switch] $DryRun
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# --- What is synced ---------------------------------------------------------------------

$MirroredDirectories = @('app', 'bootstrap', 'config', 'database', 'lang', 'resources', 'routes', 'tests', 'public', 'storage')
$RootFiles = @('artisan', 'composer.json', 'composer.lock', 'package.json', 'package-lock.json',
    'vite.config.js', 'phpunit.xml', '.editorconfig', '.env.example', 'docs/PORTAL.md')

# Owned by the KEENEY platform: never written or deleted.
$PlatformPaths = @('README.md', 'Dockerfile', '.dockerignore', 'site.json', '.trivyignore.yaml', '.npmrc',
    '.gitignore', '.gitattributes')
$PlatformPatterns = @('^\.git/', '^azure-pipelines-[^/]*\.yml$', '^pipelines/')

# Never copied, wherever they appear.
$ExcludedNames = @('CLAUDE.md', 'AGENTS.md', '.mcp.json', 'boost.json', '.env', 'auth.json', '.phpunit.result.cache')
$ExcludedDirectories = @('.claude', '.ai', '.vscode', '.idea', '.osp', 'vendor', 'node_modules', 'scripts')

$SearchPattern = 'claude|anthropic|co-authored|ai assistant|generated by|copilot|chatgpt|openai'
$SearchSkip = @('composer.lock', 'package-lock.json')
$BinaryExtensions = @('.png', '.jpg', '.jpeg', '.gif', '.ico', '.webp', '.pdf', '.ttf', '.otf', '.woff', '.woff2', '.zip')

# --- Helpers ---------------------------------------------------------------------------

function Resolve-Git {
    if ($Git -ne '') { return $Git }

    $onPath = Get-Command git -ErrorAction SilentlyContinue
    if ($null -ne $onPath) { return $onPath.Source }

    $desktop = Get-ChildItem "$env:LOCALAPPDATA\GitHubDesktop\app-*\resources\app\git\cmd\git.exe" -ErrorAction SilentlyContinue |
        Sort-Object { [version]($_.FullName -replace '^.*\\app-([0-9.]+)\\.*$', '$1') } -Descending |
        Select-Object -First 1
    if ($null -ne $desktop) { return $desktop.FullName }

    throw 'git.exe not found. Pass -Git <path>.'
}

function Invoke-Git([string] $Repository, [string[]] $Arguments) {
    $output = & $script:GitExe -C $Repository -c core.quotepath=off @Arguments
    if ($LASTEXITCODE -ne 0) { throw "git $($Arguments -join ' ') failed in $Repository" }
    return $output
}

# Files git would commit: tracked (and still present) plus untracked files that are not ignored.
function Get-RepositoryFiles([string] $Repository) {
    $paths = @(Invoke-Git $Repository @('ls-files', '--cached', '--others', '--exclude-standard')) | Sort-Object -Unique
    return @($paths | Where-Object { $_ -and (Test-Path -LiteralPath (Join-Path $Repository $_) -PathType Leaf) })
}

function Test-Platform([string] $Path) {
    if ($PlatformPaths -contains $Path) { return $true }
    foreach ($pattern in $PlatformPatterns) { if ($Path -match $pattern) { return $true } }
    return $false
}

function Test-Excluded([string] $Path) {
    $segments = $Path -split '/'
    if ($ExcludedNames -contains $segments[-1]) { return $true }
    foreach ($segment in $segments[0..($segments.Count - 1)]) {
        if ($ExcludedDirectories -contains $segment) { return $true }
    }
    if ($Path -like 'docs/*' -and $Path -ne 'docs/PORTAL.md') { return $true }
    return $false
}

# Inside the synced scope (the same rule decides what is copied and what is mirrored away).
function Test-Synced([string] $Path) {
    if (Test-Platform $Path) { return $false }
    if (Test-Excluded $Path) { return $false }
    if ($RootFiles -contains $Path) { return $true }

    $top = ($Path -split '/')[0]
    if ($MirroredDirectories -notcontains $top) { return $false }
    if ($Path -like 'public/vendor/nova/*') { return $false }
    # Storage: only the directory skeleton, i.e. its .gitignore files.
    if ($top -eq 'storage') { return (Split-Path -Leaf $Path) -eq '.gitignore' }
    return $true
}

function Test-SameContent([string] $A, [string] $B) {
    if (-not (Test-Path -LiteralPath $B -PathType Leaf)) { return $false }
    if ((Get-Item -LiteralPath $A).Length -ne (Get-Item -LiteralPath $B).Length) { return $false }
    return (Get-FileHash -LiteralPath $A -Algorithm SHA256).Hash -eq (Get-FileHash -LiteralPath $B -Algorithm SHA256).Hash
}

function Test-Binary([string] $Path) {
    return $BinaryExtensions -contains [System.IO.Path]::GetExtension($Path).ToLowerInvariant()
}

function ConvertTo-WindowsPath([string] $Root, [string] $Path) {
    return Join-Path $Root ($Path -replace '/', '\')
}

# --- Sync ------------------------------------------------------------------------------

$script:GitExe = Resolve-Git
# Default: the repository this script lives in ($PSScriptRoot is empty in Windows PowerShell 5.1 parameter defaults).
if ($Source -eq '') { $Source = Split-Path -Parent $PSScriptRoot }
$Source = (Resolve-Path $Source).Path
if (-not (Test-Path (Join-Path $Target '.git'))) { throw "$Target is not a git clone." }
$Target = (Resolve-Path $Target).Path
if ($Source -eq $Target) { throw 'Source and target are the same directory.' }

Write-Host "Source: $Source"
Write-Host "Target: $Target"
if ($DryRun) { Write-Host 'Dry run: the clone is not changed.' -ForegroundColor Yellow }

$sourceFiles = @(Get-RepositoryFiles $Source | Where-Object { Test-Synced $_ })
$sourceSet = New-Object 'System.Collections.Generic.HashSet[string]' ([StringComparer]::OrdinalIgnoreCase)
foreach ($path in $sourceFiles) { [void] $sourceSet.Add($path) }

foreach ($required in @('artisan', 'composer.json', 'composer.lock', 'public/index.php', 'docs/PORTAL.md')) {
    if (-not $sourceSet.Contains($required)) { throw "The source has no $required - refusing to sync an incomplete application." }
}

$copied = 0
foreach ($path in $sourceFiles) {
    $from = ConvertTo-WindowsPath $Source $path
    $to = ConvertTo-WindowsPath $Target $path
    if (Test-SameContent $from $to) { continue }

    Write-Host "  copy    $path"
    $copied++
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $to) | Out-Null
        Copy-Item -LiteralPath $from -Destination $to -Force
    }
}

$deleted = 0
foreach ($path in @(Get-RepositoryFiles $Target | Where-Object { (Test-Synced $_) -and -not $sourceSet.Contains($_) })) {
    Write-Host "  delete  $path"
    $deleted++
    if (-not $DryRun) {
        $file = ConvertTo-WindowsPath $Target $path
        Remove-Item -LiteralPath $file -Force
        # Drop directories the deletion left empty (inside the synced scope only).
        $directory = Split-Path -Parent $file
        while ($directory.Length -gt $Target.Length -and @(Get-ChildItem -LiteralPath $directory -Force).Count -eq 0) {
            Remove-Item -LiteralPath $directory -Force
            $directory = Split-Path -Parent $directory
        }
    }
}

if ($DryRun) {
    Write-Host "Would copy $copied file(s) and delete $deleted file(s)."
    exit 0
}
Write-Host "Copied $copied file(s), deleted $deleted file(s)."

# --- Checks on the clone ---------------------------------------------------------------

$problems = New-Object System.Collections.Generic.List[string]
$targetFiles = @(Get-RepositoryFiles $Target)

foreach ($path in @('.env', 'auth.json')) {
    if (Test-Path -LiteralPath (Join-Path $Target $path)) { $problems.Add("$path exists in the clone") }
}
foreach ($path in $targetFiles) {
    $name = ($path -split '/')[-1]
    if ($name -eq 'auth.json' -or $name -eq '.env' -or ($name -like '.env.*' -and $name -ne '.env.example')) {
        $problems.Add("$path would be committed")
    }
}

foreach ($path in $targetFiles) {
    if (Test-Binary $path) { continue }
    $file = ConvertTo-WindowsPath $Target $path
    $bytes = [System.IO.File]::ReadAllBytes($file)

    if ([Array]::IndexOf($bytes, [byte] 13) -ge 0) { $problems.Add("CRLF line endings: $path") }

    if ($SearchSkip -contains $path) { continue }
    $lineNumber = 0
    foreach ($line in [System.IO.File]::ReadAllLines($file)) {
        $lineNumber++
        if ($line -match $SearchPattern) {
            $problems.Add(('Forbidden term in {0}:{1}: {2}' -f $path, $lineNumber, $line.Trim()))
        }
    }
}

if ($problems.Count -gt 0) {
    Write-Host ''
    Write-Host 'Checks FAILED:' -ForegroundColor Red
    $problems | ForEach-Object { Write-Host "  $_" -ForegroundColor Red }
    exit 1
}
Write-Host 'Checks passed: no forbidden terms, no CRLF, no .env or auth.json.' -ForegroundColor Green

# --- Status and commit message ---------------------------------------------------------

& $script:GitExe -C $Target update-index -q --refresh | Out-Null
$status = @(Invoke-Git $Target @('status', '--short'))

Write-Host ''
Write-Host "git status ($Target):"
if ($status.Count -eq 0) {
    Write-Host '  (clean - nothing to commit)'
    exit 0
}
$status | ForEach-Object { Write-Host "  $_" }

$sourceCommit = (Invoke-Git $Source @('rev-parse', '--short', 'HEAD')) | Select-Object -First 1
$hasApplication = $null -ne (& $script:GitExe -C $Target ls-tree --name-only HEAD -- app/Nova 2>$null)
$message = if ($hasApplication) { "Update portal application to $sourceCommit" } else { 'Add ProPerx member portal application' }

if ($message.Length -gt 60 -or $message -notmatch '^(Add|Update|Fix|Remove) ') {
    throw "Suggested commit message does not follow the convention: $message"
}

Write-Host ''
Write-Host 'Suggested commit message (nothing was committed or pushed):'
Write-Host "  $message"
